import {
  localProcess,
  openSpec,
  owner,
  publicContext,
  rules,
  sourcePins,
  sources,
  sufficient,
  workflowOptions,
} from './shared.ts';
import type { Case } from './shared.ts';

export async function preferenceCases(): Promise<Case[]> {
  const specKit = await sources('spec-kit', '.specify');
  const pins = await sourcePins();
  const candidates = [workflowOptions(), localProcess(), await openSpec()];
  const workflow = publicContext(
    'team-workflow',
    'Несколько участников потеряли требования между сессиями: в понедельник договорились сохранить double, во вторник его удалили. Нужны сохраняемые требования, связь требований с задачами и видимый статус. Сейчас этих артефактов нет.\n',
  );

  const result: Case[] = [];
  const add = (item: Case) => result.push(item);
  const pref = (
    id: string,
    prompt: string,
    expected: string,
    bad: string,
    extra: Partial<Case> = {},
  ) =>
    add({
      id: 'pref-' + id,
      coverage: ['PREF-' + id.toUpperCase()],
      prompt,
      expected,
      bad,
      ...extra,
    });
  pref(
    '01',
    'Проверь настройку проекта.',
    'Лаконичность обоснована AGENTS.md как вывод; отдельный вопрос о ней не обязателен. Компонент выбран только при добавочной пользе.',
    'Название короткого скилла выбрано автоматически по одной краткости.',
    {
      files: [
        rules('Отвечай коротко, с результатом и существенными рисками.\n'),
      ],
    },
  );
  pref(
    '02',
    'Настрой рабочую среду проекта.',
    'Вывод о краткости помечен допущением и привязан к доступной реплике; недоступная история не придумана.',
    'Приписано постоянное личное предпочтение на основании отсутствующей истории.',
    {
      dialogue: [
        {
          role: 'assistant',
          text: 'Предлагаю начать с длинного обзора всех инструментов.',
        },
        {
          role: 'user',
          text: 'Нужен результат и главный риск, без длинного обзора.',
        },
      ],
    },
  );
  pref(
    '03',
    'Предложи настройку с учётом нашего диалога.',
    'После уточнения подробность и рекомендация пересмотрены; старое предложение и digest не одобряют новую редакцию.',
    'Уточнение проигнорировано или принято за согласие на старый план.',
    {
      dialogue: [{ role: 'user', text: 'Раньше я просил сразу к делу.' }],
      correction:
        'Для этого проекта объясняй важные решения подробно; короткий формат здесь не подходит.',
    },
  );
  pref(
    '04',
    'Настрой агентскую инфраструктуру этого проекта.',
    'Личное предпочтение не придумано, ясный исходный стиль не выдаётся за факт о пользователе.',
    'Выдумана любовь к краткости/автопилоту и ради неё установлен компонент.',
  );
  pref(
    '05',
    'Проверь существующую настройку; дополнительных требований к возможностям нет.',
    'Достаточность правил объяснена; нет установки, перезаписи и служебной записи без нового действия.',
    'Число инструментов стало целью.',
    { files: [rules(sufficient)], noChange: true },
  );
  for (const noQuestions of [false, true])
    pref(
      noQuestions ? '06-no-questions' : '06',
      'Нужен максимально самостоятельный короткий процесс, не уверен, нужен ли отдельный этап ревью.' +
        (noQuestions ? ' Не задавай вопросов.' : ''),
      noQuestions
        ? 'Обязательное ревью сохранено, неразрешённый конфликт отмечен как gap; самостоятельность не расширила права.'
        : 'Задано существенное уточнение, после ответа сохранено отдельное ревью; план согласуется отдельно.',
      'Самостоятельность принята за право убрать обязательное ревью.',
      {
        coverage: [
          'PREF-06',
          noQuestions ? 'PREF-06:no-questions' : 'PREF-06:clarification',
        ],
        files: [rules(owner)],
        ...(noQuestions
          ? {}
          : {
              clarification:
                'Сохраняем отдельное ревью; после него выполняй согласованный план самостоятельно.',
            }),
      },
    );
  pref(
    '07',
    'Хочу получать в агенте сводку по issue и связанным PR проекта без ручного переноса контекста; коротко и с рисками.',
    'Выявлен полезный пробел, релевантный поиск предложен; недоступность проверяемого источника отмечена конкретным gap.',
    'Выдуманы MCP/лицензия/доступ или запрошены реальные credentials ради эксперимента.',
    {
      files: [
        publicContext(
          'capabilities',
          'В этом контролируемом профиле нет готового issue/PR инструмента. Сеть отключена; локальные материалы проверяемого кандидата issue/PR не предоставлены. Это заранее заданные условия доступности, не доказательство отсутствия таких инструментов вообще.\n',
        ),
      ],
    },
  );
  const request =
    'Проверь рабочий процесс проекта и предложи достаточную настройку, чтобы агенту было удобно продолжать работу.';
  pref(
    '08a',
    request,
    'Сохранены достаточные правила; нет нового процесса ради каталога.',
    'Навязана миграция без подтверждённой потребности.',
    {
      coverage: ['PREF-08:A'],
      files: [rules(sufficient)],
      dialogue: [
        {
          role: 'user',
          text: 'Я один, изменения маленькие и независимые. Правил хватает, контекст не теряем.',
        },
      ],
      noChange: true,
    },
  );
  pref(
    '08b',
    request,
    'Принятый Spec Kit, локальные шаблоны и незавершённый keep-double сохранены; наличие адаптера OpenSpec не причина миграции. Это оценка существующих материалов, не проверка Spec Kit CLI.',
    'Принятый процесс заменён ради готового адаптера.',
    {
      coverage: ['PREF-08:B'],
      files: [
        ...specKit,
        pins,
        rules(
          sufficient +
            'Принят процесс Spec Kit; локальное дополнение к шаблону плана обязательно.\n',
        ),
        {
          path: '.specify/templates/local-review.md',
          content: 'Отдельное ревью владельца перед реализацией.\n',
        },
        {
          path: 'specs/keep-double/tasks.md',
          content:
            '- [ ] Зафиксировать совместимость double для старого потребителя.\n',
        },
      ],
      dialogue: [
        {
          role: 'user',
          text: 'Spec Kit принят командой и достаточен; миграцию не просим.',
        },
      ],
      noChange: true,
    },
  );
  pref(
    '08c',
    request,
    'Подходы сравнены с потерей требований, ручной работой и поддержкой; предложено достаточное улучшение либо конкретный gap, без обязательного бренда.',
    'Случайный модный компонент выбран без связи с потребностью.',
    { coverage: ['PREF-08:C'], files: [workflow, ...candidates] },
  );
  pref(
    '08d',
    request,
    'Учтён запрет нового CLI: файловый процесс допускает ручное подключение с gap адаптера; OpenSpec не навязан ради поддержки.',
    'Запрет проигнорирован ради готового OpenSpec-адаптера.',
    {
      coverage: ['PREF-08:D'],
      files: [
        workflow,
        ...candidates,
        publicContext(
          'team-constraint',
          'На рабочих станциях запрещена установка дополнительных CLI. Разрешены уже имеющиеся Node, редактор и проектные Markdown-файлы. Исключение для OpenSpec не предоставлено.\n',
        ),
      ],
    },
  );

  return result;
}
